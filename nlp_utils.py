def preprocess_text(text: str) -> str:
    """Removes links and special characters from the text and standardizes the case of the words."""
    if not text:
        return ""
    
    text = text.lower()
    
    text = re.sub(r'https?://\S+|www\.\S+|t\.me/\S+', '', text)
    text = re.sub(r'[^[^а-яіїєґa-z0-9\s]\s]', ' ', text)
    
    words = text.split()
    cleaned_words = [word for word in words if word not in STOP_WORDS and len(word) > 2]
    
    return " ".join(cleaned_words)